cask "visual-studio-code@insiders" do
  arch arm: "-arm64"

  version "1.134.0-insider,1786645522971,0f3c3b53028901b912211a99b23232b76017bcfc"
  sha256 arm:   "4126c0093d6dd731b95944cb6bb90013fe9bde78f61d6ebc036384d450bf21fc",
