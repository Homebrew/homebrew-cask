  version "0.0.46-nightly.20261012.3021"
  sha256 arm:          "261558500dd954f3ffb14c7c6b04f3e5d9d702425870351c9c141023636ef247",
         intel:        "69baa9f3062bf1e4dd7e202370e3458b921ac22cbd15b809b8e84dcee0cd1800",
