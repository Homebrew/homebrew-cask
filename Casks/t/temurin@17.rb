  sha256 arm:   "ab0bd83d1af973b8c4846b3939a1cbd71474fb07cf817074e1f9e8e40e97eb29",
         intel: "de08f77e8a715abadf0498cbca8255a47c63c6a9ee2ca27d26efee2640c0a5f8"

  on_arm do
    version "17.0.21,9"
  end
  on_intel do
    version "17.0.21,9"
  end

