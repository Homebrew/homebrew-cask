  sha256 arm:   "7e990543a11e4a0895bd295d62bc94e4374fbf0512e7b4cb8944c0cd6d4da4de",
         intel: "660fbb14606693c37264d220dc19c5f796d85cac403c21c0502ba47f68d4c5b7"

  on_arm do
    version "17.0.21.1,2"
  end
  on_intel do
    version "17.0.21.1,2"
  end

